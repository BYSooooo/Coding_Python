## Lists

# List
day_of_week = ["Mon", "Tue", "Wed", "Thu", "Fri"]

# Check Method of List by Typing '.' after List
#day_of_week.

# Count Method
wed_count = day_of_week.count("Wed")
print(wed_count) # 1

# Clear Method
day_of_week_1 = ["Mon", "Tue", "Wed", "Thu", "Fri"]
day_of_week_1.clear()
print(day_of_week_1) # []

# Reverse
day_of_week_2 = ["Mon", "Tue", "Wed", "Thu", "Fri"]
day_of_week_2.reverse()
print(day_of_week_2) #['Fri', 'Thu', 'Wed', 'Tue', 'Mon']

# Append
day_of_week_3 = ["Mon", "Tue", "Wed", "Thu", "Fri"]
day_of_week_3.append("Sat")
print(day_of_week_3)
day_of_week_3.append("Sun")
print(day_of_week_3)

# Select Element using index
day_of_week_4 = ["Mon", "Tue", "Wed", "Thu", "Fri"]
third_item = day_of_week_4[2]
print(third_item)


