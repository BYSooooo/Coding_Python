## Methods

name = 'nico'

# print() = Function
# .upper() = Method (Change Data to Upper Case)
print(name.upper()) # NICO

#.capitalize() = Method (Change First Character to Upper Case)
print(name.capitalize()) # Nico

# .endswidth() = Method (return boolean value by checking data's last character equals argument value )
print(name.endswith('o')) # True

